"""The one-click script a registered automation hands you.

Registering an automation ends with a file you can double-click:
``config/automations/<name>/run.bat``. It exists so that running the automation
does not require remembering a command line, a working directory, or which
Python is the right one - three things that are easy to get wrong at 5pm and
very visible when you do (the run starts in the wrong folder, or ``python`` is
the Windows Store stub).

What the script does is deliberately boring: call ``cli.py automation run`` with
a values file, print the exit code with its meaning, and wait so the window does
not vanish. It contains no automation logic at all - it runs the same code path
``automation run`` uses, so there is one behaviour, not two.

The run always starts from the screen FACT is showing (``--from-screen``). A
record posted while the app is already open on the list, or on a half-opened
form, is the normal case, so the launcher must not insist on the first step:
sending FACT back to the login screen would undo the operator's own navigation.
"""

from __future__ import annotations

from pathlib import Path

from core.automation.registry import automations_root as automations_root_of
from core.automation.registry import validate_name
from core.config import project_root

#: The generated file's name, beside the automation it runs.
LAUNCHER_NAME = "run.bat"

#: Where the launcher looks for record values when it is given no argument.
VALUES_NAME = "values.json"

EXIT_MEANING = "0 saved, 1 failed or unconfirmed, 2 blocked, 3 stopped"


def launcher_path(
    name: str,
    automations_root: str | Path | None = None,
) -> Path:
    """Where one automation's launcher belongs."""
    return automations_root_of(automations_root) / validate_name(name) / LAUNCHER_NAME


def launcher_for(
    name: str,
    automations_root: str | Path | None = None,
) -> Path | None:
    """The existing launcher, or ``None`` when the automation has none yet."""
    path = launcher_path(name, automations_root)
    return path if path.is_file() else None


def _python(project: Path, python_exe: str | None) -> str:
    """The interpreter to run: the project's venv when it has one."""
    if python_exe:
        return python_exe
    candidate = project / "myvenv" / "Scripts" / "python.exe"
    return str(candidate) if candidate.is_file() else "python"


def render_launcher(
    name: str,
    *,
    project: str | Path | None = None,
    python_exe: str | None = None,
    values_name: str = VALUES_NAME,
) -> str:
    """The launcher's text, with CRLF line endings as cmd.exe expects."""
    validate_name(name)
    root = Path(project) if project is not None else project_root()
    python = _python(root, python_exe)
    lines = [
        "@echo off",
        "setlocal",
        f"rem FACT automation launcher: {name}",
        f"rem Generated by `python cli.py automation script {name}`; edit freely.",
        f"title FACT automation - {name}",
        "",
        "rem run from the project folder, whatever folder the click came from",
        f'cd /d "{root}"',
        "",
        f'set "PY={python}"',
        'if not exist "%PY%" set "PY=python"',
        "",
        "rem the first argument is a values file; without one, look beside this script",
        'set "VALUES=%~1"',
        f'if "%VALUES%"=="" set "VALUES=%~dp0{values_name}"',
        'if not exist "%VALUES%" (',
        '  echo [ERROR] no values file: "%VALUES%"',
        "  echo         put one beside this script, or drag one onto it.",
        '  if "%~1"=="" pause',
        "  exit /b 2",
        ")",
        "",
        f"echo FACT automation: {name}",
        'echo   values: "%VALUES%"',
        "echo   stop: Alt+T  pause: Alt+P  resume: Alt+R",
        "echo.",
        "",
        "rem start at the step the screen belongs to, not at step 1",
        f'"%PY%" "cli.py" automation run {name} --values "%VALUES%" --from-screen',
        "",
        "rem keep the window open when the script was double-clicked",
        'set "CODE=%ERRORLEVEL%"',
        "echo.",
        f"echo Exit code %CODE% ^({EXIT_MEANING}^)",
        'if "%~1"=="" pause',
        "endlocal & exit /b %CODE%",
    ]
    return "\r\n".join(lines) + "\r\n"


def write_launcher(
    name: str,
    *,
    project: str | Path | None = None,
    automations_root: str | Path | None = None,
    python_exe: str | None = None,
    values_name: str = VALUES_NAME,
) -> Path:
    """Write the launcher beside the automation; returns its path."""
    path = launcher_path(name, automations_root)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        render_launcher(
            name, project=project, python_exe=python_exe, values_name=values_name
        ),
        encoding="ascii",
        newline="",
    )
    return path


__all__ = [
    "EXIT_MEANING",
    "LAUNCHER_NAME",
    "VALUES_NAME",
    "launcher_for",
    "launcher_path",
    "render_launcher",
    "write_launcher",
]
